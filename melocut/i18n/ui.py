HERE = os.path.dirname(os.path.abspath(__file__))
SITE = os.path.join(HERE, '..', 'site')
src = open(os.path.join(SITE, 'assets', 'app.js'), encoding='utf8').read()
keys = []
for m in re.finditer(r"T\('((?:[^'\\]|\\.)*)'", src):
    k = m.group(1).replace("\\'", "'")
    if k not in keys: keys.append(k)
ok = True
for name, d in (('es', ES), ('pt-br', PT)):
    missing = [k for k in keys if k not in d]
    extra = [k for k in d if k not in keys]
    for k in d:  # every {n} slot must survive translation
        if sorted(re.findall(r'\{\d\}', k)) != sorted(re.findall(r'\{\d\}', d[k])): print(f'{name}: slots differ: {k!r}'); ok = False
    if missing or extra: print(f'{name}: missing {missing} extra {extra}'); ok = False
    os.makedirs(os.path.join(SITE, 'assets', 'i18n'), exist_ok=True)
    with open(os.path.join(SITE, 'assets', 'i18n', f'{name}.js'), 'w', encoding='utf8') as f:
        f.write('// Generated by i18n/ui.py. Interface text for the tools, keyed by the English text.\n')
        f.write('window.MELOCUT_I18N = ' + json.dumps(d, ensure_ascii=False, indent=0) + ';\n')
print(f'{len(keys)} keys', 'OK' if ok else 'PROBLEMS')
sys.exit(0 if ok else 1)
